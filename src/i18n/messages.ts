const DICTS: Record<Lang, Partial<Messages>> = {
  "pt-BR": ptBR,
  "pt-PT": { ...ptBR, ...ptPT },
  "en-US": enUS,
  "en-GB": { ...enUS, ...enGB },
  es,
  de,
  fr,
  it,
  nl,
  pl,
  ru,
  tr,
  uk,
  ja,
  "zh-CN": zhCN,
};

export type TFunction = (key: MessageKey, vars?: Record<string, string>) => string;

/** Fallback de texto: idioma → en-US → pt-BR → chave (igual ao app Android). */
export function translator(lang: Lang): TFunction {
  const dict = DICTS[lang];
  return (key, vars) => {
    let s = dict[key] ?? enUS[key] ?? ptBR[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}
